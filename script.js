function setLanguage(language) {

    if (!translations[language]) {
        language = "ar";
    }

    const dictionary = translations[language];

    /*
       Change document language
    */

    document.documentElement.lang = language;


    /*
       Arabic = RTL
       French / English = LTR
    */

    if (language === "ar") {

        document.documentElement.dir = "rtl";

    } else {

        document.documentElement.dir = "ltr";

    }


    /*
       Translate elements
    */

    const elements =
        document.querySelectorAll("[data-i18n]");

    elements.forEach(element => {

        const key =
            element.getAttribute("data-i18n");

        if (!dictionary[key]) {
            return;
        }

        element.innerHTML =
            dictionary[key];

    });


    /*
       Update language selector
    */

    if (languageSelector) {

        languageSelector.value =
            language;

    }


    /*
       Save language
    */

    localStorage.setItem(
        "yofaKidsLanguage",
        language
    );


    /*
       Update page title
    */

    if (language === "ar") {

        document.title =
            "YOFA Kids | منصة التعليم الابتدائي";

    } else if (language === "fr") {

        document.title =
            "YOFA Kids | Plateforme éducative";

    } else {

        document.title =
            "YOFA Kids | Primary Learning Platform";

    }

}


